"""Write docs/MODEL_REPORT.md and the README's results from the training artifacts.

Run from backend/: python -m scripts.build_report

Every number in those documents comes from artifacts/metrics.json or error_analysis.json,
so they can't drift from what the model actually did. tests/test_model_report.py fails if
the committed documents are out of date. To change the wording, edit
scripts/model_report_template.md, never the generated file.
"""

import json
import re
from collections import Counter
from pathlib import Path

from app.ml.features import FEATURE_NAMES

BACKEND_DIR = Path(__file__).resolve().parent.parent
REPO_DIR = BACKEND_DIR.parent
ARTIFACTS_DIR = BACKEND_DIR / "artifacts"
TEMPLATE_PATH = Path(__file__).resolve().parent / "model_report_template.md"
REPORT_PATH = REPO_DIR / "docs" / "MODEL_REPORT.md"
README_PATH = REPO_DIR / "README.md"
README_START = "<!-- model-results:start (generated by scripts/build_report.py) -->"
README_END = "<!-- model-results:end -->"

# A gap this small can't be told apart from noise on a test set this size.
CLOSE_CALL_ERRORS = 2

PLACEHOLDER = re.compile(r"\{\{([\w.]+)(?:\|([^}]+))?\}\}")
NUMBER_WORDS = ["no", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"]


def words(count: int) -> str:
    return NUMBER_WORDS[count] if 0 <= count < len(NUMBER_WORDS) else str(count)


def plural(count: int, singular: str, many: str | None = None) -> str:
    return f"{words(count)} {singular if count == 1 else (many or singular + 's')}"


def title(name: str) -> str:
    return name.replace("_", " ").title()


def errors_of(result: dict) -> int:
    return result["confusion_matrix"]["fp"] + result["confusion_matrix"]["fn"]


def threshold_f1(metrics: dict, threshold: float) -> float:
    rows = metrics["baseline"]["train_thresholds"]
    return next(row["f1"] for row in rows if abs(row["threshold"] - threshold) < 1e-9)


def headline(metrics: dict) -> str:
    baseline, model = metrics["test"]["baseline"], metrics["test"]["model"]
    gap = errors_of(baseline) - errors_of(model)
    total = metrics["dataset"]["test_applications"]
    scores = (
        f"the chosen model ({title(metrics['model_name'])}) scores F1 {model['f1']:.3f} on the test set against "
        f"{baseline['f1']:.3f} for a one-line skill-coverage rule."
    )
    if gap > CLOSE_CALL_ERRORS:
        return f"{scores} The model makes {words(gap)} fewer errors out of {total}."
    if gap > 0:
        return (
            f"{scores} That gap is **{plural(gap, 'application')} out of {total}**. The model is not meaningfully "
            "better than the baseline on this data, and this report does not claim it is."
        )
    if gap == 0:
        return f"{scores} Both make the same number of errors out of {total}, so the model is not better than the baseline."
    return f"{scores} The model makes {words(-gap)} more errors out of {total}, so the baseline is the better choice on this data."


def comparison_sentence(metrics: dict) -> str:
    baseline, model = metrics["test"]["baseline"]["confusion_matrix"], metrics["test"]["model"]["confusion_matrix"]
    real_matches = model["tp"] + model["fn"]
    if baseline["tp"] == model["tp"]:
        found = f"Both approaches find {model['tp']} of the {real_matches} true matches."
    else:
        found = f"The baseline finds {baseline['tp']} of the {real_matches} true matches, and the model finds {model['tp']}."
    alarms = baseline["fp"] - model["fp"]
    if alarms > 0:
        return f"{found} The model has {plural(alarms, 'fewer false positive', 'fewer false positives')}."
    if alarms < 0:
        return f"{found} The model has {plural(-alarms, 'more false positive', 'more false positives')}."
    return f"{found} They have the same number of false positives."


def test_versus_cv_sentence(metrics: dict) -> str:
    test_f1, cv_f1 = metrics["test"]["model"]["f1"], metrics["chosen_model"]["mean_cv_f1"]
    real_matches = metrics["test"]["model"]["confusion_matrix"]["tp"] + metrics["test"]["model"]["confusion_matrix"]["fn"]
    if test_f1 > cv_f1:
        return (
            f"The test F1 ({test_f1:.2f}) is higher than the CV F1 ({cv_f1:.2f}). That is most likely luck from a small "
            f"test set with only {real_matches} positives, so {cv_f1:.2f} is the more cautious estimate of what to expect."
        )
    return f"The test F1 ({test_f1:.2f}) is close to or below the CV F1 ({cv_f1:.2f}), so {test_f1:.2f} is the more cautious estimate."


def selection_sentence(metrics: dict) -> str:
    results = metrics["cross_validation"]["best_by_model"]
    chosen = metrics["model_name"]
    other = next(name for name in results if name != chosen)
    gap = results[chosen] - results[other]
    spread = best_std(metrics, chosen)
    label = title(chosen)
    text = f'The rule fixed in advance was "highest mean CV F1", so {label} was selected.'
    if gap < spread:
        text += (
            f" The honest reading is that this is a tie: the {gap:.3f} gap is far smaller than the {spread:.3f} variation "
            "between folds."
        )
    return text


def best_std(metrics: dict, name: str) -> float:
    return max(metrics["cross_validation"]["results"][name], key=lambda result: result["mean_f1"])["std_f1"]


def params_text(params: dict) -> str:
    return ", ".join(f"`{key}={value}`" for key, value in params.items())


def cv_table(metrics: dict) -> str:
    rows = ["| Model | Best parameters | Mean CV F1 | Std across folds |", "|---|---|---|---|"]
    results = metrics["cross_validation"]["results"]
    for name in sorted(results, key=lambda key: -metrics["cross_validation"]["best_by_model"][key]):
        best = max(results[name], key=lambda result: result["mean_f1"])
        mean = f"{best['mean_f1']:.3f}"
        if name == metrics["model_name"]:
            mean = f"**{mean}**"
        rows.append(f"| {title(name)} | {params_text(best['params'])} | {mean} | {best['std_f1']:.3f} |")
    return "\n".join(rows)


def results_table(metrics: dict) -> str:
    baseline, model = metrics["test"]["baseline"], metrics["test"]["model"]
    label = title(metrics["model_name"])
    return "\n".join(
        [
            "| Test set, class 1 | Precision | Recall | F1 |",
            "|---|---|---|---|",
            f"| Baseline (`required_overlap_ratio >= {metrics['baseline']['threshold']:.3f}`) | "
            f"{baseline['precision']:.3f} | {baseline['recall']:.3f} | {baseline['f1']:.3f} |",
            f"| {label} | {model['precision']:.3f} | {model['recall']:.3f} | {model['f1']:.3f} |",
        ]
    )


def confusion_table(metrics: dict) -> str:
    rows = [
        "| Confusion matrix | Actual 0, predicted 0 | Actual 0, predicted 1 | Actual 1, predicted 0 | Actual 1, predicted 1 |",
        "|---|---|---|---|---|",
    ]
    for label, key in (("Baseline", "baseline"), (title(metrics["model_name"]), "model")):
        matrix = metrics["test"][key]["confusion_matrix"]
        rows.append(f"| {label} | {matrix['tn']} | {matrix['fp']} | {matrix['fn']} | {matrix['tp']} |")
    return "\n".join(rows)


def most_common_share(errors: list[dict]) -> tuple[str, int]:
    shape = Counter(f"{error['required_skills_total'] - len(error['missing_required_skills'])} of {error['required_skills_total']}" for error in errors)
    return shape.most_common(1)[0]


def describe_errors(errors: list[dict], kind: str, threshold: float) -> str:
    """Plain sentences about one kind of error, stating only what the counts show."""
    if not errors:
        return f"There were no {kind} on the test set."
    count = len(errors)
    shape, shape_count = most_common_share(errors)
    meets = sum(error["meets_experience"] for error in errors)
    has_all = sum(not error["missing_required_skills"] for error in errors)
    probabilities = [error["predicted_probability"] for error in errors]
    close_to_threshold = sum(abs(probability - threshold) <= 0.1 for probability in probabilities)
    jobs = Counter(error["job_title"] for error in errors).most_common(1)[0]
    parts = [
        f"**{plural(count, kind[:-1], kind).capitalize()}.** {shape_count} of {count} had {shape} required skills, and "
        f"{has_all} of {count} had every required skill.",
        f"{meets} of {count} met the experience minimum.",
        f"Predicted probabilities ran from {min(probabilities):.2f} to {max(probabilities):.2f}, with {close_to_threshold} of "
        f"{count} within 0.10 of the {threshold:g} threshold.",
    ]
    if jobs[1] > 1:
        parts.append(f"The most affected job was {jobs[0]}, with {jobs[1]} of {count}.")
    return " ".join(parts)


def interpretation(false_positives: list[dict], false_negatives: list[dict]) -> str:
    """What the counts suggest, only saying what they actually support."""
    sentences = []
    alarms_with_skills = sum(len(error["missing_required_skills"]) <= 1 for error in false_positives)
    if false_positives and alarms_with_skills == len(false_positives):
        sentences.append(
            f"Every false alarm was missing at most one required skill, yet its label said Needs Review. The model is "
            "following the main signal in the data here, and the labels are intentionally noisy, so these look more like "
            "label noise than a blind spot."
        )
    elif false_positives and alarms_with_skills * 2 > len(false_positives):
        sentences.append(
            f"{alarms_with_skills} of {len(false_positives)} false alarms were missing at most one required skill, yet their "
            "labels said Needs Review. That fits the intentionally noisy labels, though this report can't prove it."
        )
    misses_lacking_skills = sum(bool(error["missing_required_skills"]) for error in false_negatives)
    if false_negatives and misses_lacking_skills == len(false_negatives):
        sentences.append(
            "Every missed match lacked at least one required skill, so its label said Potential Match despite the gap in "
            "skill coverage."
        )
    sentences.append(
        f"With only {len(false_positives) + len(false_negatives)} errors, these are observations rather than reliable patterns. "
        "They weren't used to change the model, because that would turn the test set into training data."
    )
    return " ".join(sentences)


def error_table(errors: list[dict]) -> str:
    rows = [
        "| Application | Type | Job | Required skills held | Missing | Experience / minimum | Probability | True label |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for error in errors:
        total = error["required_skills_total"]
        held = total - len(error["missing_required_skills"])
        missing = ", ".join(error["missing_required_skills"]) or "none"
        kind = "False alarm" if error["error_type"] == "false_positive" else "Missed match"
        rows.append(
            f"| {error['application_id']} | {kind} | {error['job_title']} | {held} of {total} | {missing} | "
            f"{error['experience_years']:g} / {error['minimum_experience_years']:g} yr | "
            f"{error['predicted_probability']:.2f} | {error['true_label']} |"
        )
    return "\n".join(rows)


def build_context(metrics: dict, error_analysis: dict) -> dict:
    errors = error_analysis["errors"]
    false_positives = [error for error in errors if error["error_type"] == "false_positive"]
    false_negatives = [error for error in errors if error["error_type"] == "false_negative"]
    results = metrics["cross_validation"]["results"]
    fully_grown = [result["mean_f1"] for result in results["random_forest"] if result["params"].get("min_samples_leaf") == 1]
    dataset = metrics["dataset"]
    return {
        **metrics,
        "derived": {
            "model_label": title(metrics["model_name"]),
            "headline": headline(metrics),
            "comparison": comparison_sentence(metrics),
            "test_versus_cv": test_versus_cv_sentence(metrics),
            "selection": selection_sentence(metrics),
            "baseline_f1_all_skills": threshold_f1(metrics, 1.0),
            "baseline_f1_half": threshold_f1(metrics, 0.5),
            "fully_grown_low": min(fully_grown),
            "fully_grown_high": max(fully_grown),
            "cv_table": cv_table(metrics),
            "results_table": results_table(metrics),
            "confusion_table": confusion_table(metrics),
            "total_applications": dataset["train_applications"] + dataset["test_applications"],
            "feature_count": len(FEATURE_NAMES),
            "negative_rate": 1 - dataset["test_positive_rate"],
            "all_required_mismatch_rate": 1 - dataset["train_match_rate_with_all_required"],
            "false_alarm_summary": describe_errors(false_positives, "false alarms", metrics["decision_threshold"]),
            "missed_match_summary": describe_errors(false_negatives, "missed matches", metrics["decision_threshold"]),
            "error_interpretation": interpretation(false_positives, false_negatives),
            "error_table": error_table(errors),
        },
    }


def _resolve(context: dict, path: str):
    value = context
    for key in path.split("."):
        value = value[key]
    return value


def render(template: str, context: dict) -> str:
    def replace(match: re.Match) -> str:
        value = _resolve(context, match.group(1))
        return format(value, match.group(2)) if match.group(2) else str(value)

    return PLACEHOLDER.sub(replace, template)


def load_artifacts() -> tuple[dict, dict]:
    metrics = json.loads((ARTIFACTS_DIR / "metrics.json").read_text(encoding="utf-8"))
    error_analysis = json.loads((ARTIFACTS_DIR / "error_analysis.json").read_text(encoding="utf-8"))
    return metrics, error_analysis


def build_report() -> str:
    metrics, error_analysis = load_artifacts()
    return render(TEMPLATE_PATH.read_text(encoding="utf-8"), build_context(metrics, error_analysis))


def build_readme(current: str) -> str:
    """Replace only the marked results block, leaving the rest of the README alone."""
    metrics, _ = load_artifacts()
    start, end = current.index(README_START), current.index(README_END)
    baseline, model = metrics["test"]["baseline"], metrics["test"]["model"]
    gap = errors_of(baseline) - errors_of(model)
    if 0 < gap <= CLOSE_CALL_ERRORS:
        summary = (
            f"The model beats a one-line rule by {plural(gap, 'application')} out of {metrics['dataset']['test_applications']}, "
            "which isn't a meaningful difference. The labels are mostly driven by skill coverage, so a simple rule already "
            "captures most of the signal."
        )
    else:
        summary = "The labels are mostly driven by skill coverage, so a simple rule already captures most of the signal."
    block = f"{README_START}\n{results_table(metrics)}\n\n{summary} The full results and limitations\nare in [docs/MODEL_REPORT.md](docs/MODEL_REPORT.md).\n"
    return current[:start] + block + current[end:]


def main() -> None:
    REPORT_PATH.write_text(build_report(), encoding="utf-8", newline="\n")
    README_PATH.write_text(build_readme(README_PATH.read_text(encoding="utf-8")), encoding="utf-8", newline="\n")
    print(f"Wrote {REPORT_PATH} and updated {README_PATH}")


if __name__ == "__main__":
    main()
